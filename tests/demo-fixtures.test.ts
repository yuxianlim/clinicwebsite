import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

test('explicit demo fixtures connect learner records without inventing Stripe events and verify fictional kiosk codes safely', async () => {
  const root = mkdtempSync(path.join(os.tmpdir(), 'workflow-fixtures-'));
  process.env.AUDIT_LOG_DB_PATH = path.join(root, 'audit.sqlite');
  process.env.CLINIC_APPOINTMENTS_DB_PATH = path.join(root, 'appointments.sqlite');
  process.env.ENABLE_DEVELOPMENT_CEU_DEMO = 'true';
  process.env.ENABLE_DEVELOPMENT_INTEGRATION_SIMULATORS = 'true';
  const learning = await import('../app/lib/learningStore.server');
  const kiosk = await import('../app/lib/demoKiosk.server');
  const audit = await import('../app/lib/auditStore.server');
  const appointments = await import('../app/lib/appointmentStore.server');
  try {
    const result = learning.seedLearningFixtures();
    assert.equal(learning.seedLearningFixtures().email, result.email);
    const evidence = learning.learningEvidence();
    assert.equal(evidence.accounts, 1);
    assert.equal(evidence.fixturePurchases, 1);
    assert.equal(evidence.paidPurchases, 1);
    assert.equal(evidence.completedVideoBlocks, 1);
    assert.equal(evidence.examAttempts, 1);
    assert.equal(evidence.certificates, 1);
    assert.equal(audit.getLatestVerifiedStripeEvent(), null, 'fixture purchase never becomes trusted Stripe evidence');
    const user = learning.authenticateLearner(result.email, result.password);
    const course = learning.learningAccount(user).courses[0];
    assert.equal(course.fixture, true);
    assert.ok(course.certificateId);
    assert.equal(learning.learningDocument(user.id, 'certificate', course.certificateId!).fixture, true);
    assert.throws(() => learning.acceptLearningPayment({ purchaseId: course.purchaseId!, intentId: 'pi_fake', eventId: 'evt_fake', amount: 9500, currency: 'usd', livemode: false }));
    const patient = kiosk.seedDemoKiosk();
    assert.equal(kiosk.seedDemoKiosk().phone, patient.phone);
    const challenge = kiosk.requestDemoCode(patient.lastFour);
    assert.equal(challenge.requiresFullPhone, false);
    if (challenge.requiresFullPhone) throw new Error('Fixture suffix is not unique.');
    assert.equal('patient' in challenge, false);
    assert.equal('appointment' in challenge, false);
    const wrong = challenge.demoCode === '000000' ? '111111' : '000000';
    for (let index = 0; index < 5; index++) assert.throws(() => kiosk.verifyDemoCode(challenge.challengeId, wrong));
    assert.throws(() => kiosk.verifyDemoCode(challenge.challengeId, challenge.demoCode));
    const now = Date.now();
    const expired = kiosk.requestDemoCode(patient.lastFour, '', now);
    if (expired.requiresFullPhone) throw new Error('Unexpected ambiguity.');
    assert.throws(() => kiosk.verifyDemoCode(expired.challengeId, expired.demoCode, now + 300_000));
    audit.createClinicPatient({ firstName: 'Fictional', lastName: 'Collision', phone: `650555${patient.lastFour}`, sessionId: null });
    assert.equal(kiosk.requestDemoCode(patient.lastFour).requiresFullPhone, true);
    assert.throws(() => kiosk.requestDemoCode(patient.lastFour, `650555${patient.lastFour}`), /Real patient records are not accepted/);
    const resolved = kiosk.requestDemoCode(patient.lastFour, patient.phone);
    if (resolved.requiresFullPhone) throw new Error('Full-phone fallback did not resolve ambiguity.');
    const verified = kiosk.verifyDemoCode(resolved.challengeId, resolved.demoCode);
    assert.ok(verified.checkInToken);
    assert.throws(() => kiosk.verifyDemoCode(resolved.challengeId, resolved.demoCode));
    assert.equal(appointments.checkInServerAppointment(verified.appointment.id, verified.checkInToken).ok, true);
    assert.equal(appointments.checkInServerAppointment(verified.appointment.id, verified.checkInToken).ok, false);
    const card = kiosk.seedDemoKiosk('card');
    assert.equal(kiosk.seedDemoKiosk('card').cardToken, card.cardToken);
    const wrongCard = `${card.cardToken.slice(0, -1)}${card.cardToken.endsWith('A') ? 'B' : 'A'}`;
    assert.throws(() => kiosk.verifyDemoCard(wrongCard));
    const cardMatch = kiosk.verifyDemoCard(card.cardToken);
    const simulated = kiosk.simulateNfcTap();
    assert.equal(simulated.reader.source, 'simulated-device');
    assert.equal(simulated.reader.model, 'ACS ACR1252U');
    assert.equal(simulated.reader.card, 'NTAG213');
    assert.equal(simulated.appointment.id, cardMatch.appointment.id);
    assert.ok(audit.getLatestAuditEvent('check-in', ['Simulated NFC tap received']));
    assert.notEqual(cardMatch.patient.id, verified.patient.id);
    assert.equal(cardMatch.patient.name, 'Fictional Card Check');
    assert.equal(appointments.checkInServerAppointment(cardMatch.appointment.id, cardMatch.checkInToken).ok, true);
    assert.throws(() => kiosk.verifyDemoCard(card.cardToken), /No eligible/);
    const freshCard = kiosk.seedDemoKiosk('card');
    assert.equal(freshCard.cardToken, card.cardToken);
    assert.notEqual(kiosk.verifyDemoCard(freshCard.cardToken).appointment.id, cardMatch.appointment.id, 'a new test appointment is prepared without changing completed check-ins');
    assert.equal(audit.getAuditStoreStatus().chainValid, true);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
